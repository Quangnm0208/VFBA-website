#!/usr/bin/env node
/**
 * Writes the Vercel Build Output API (v3) tree for the VBFA Admin project: `npm run build` = `sanity build` + this script.
 *
 *   .vercel/output/static/                      the built Studio (dist/)
 *   .vercel/output/functions/api/portal.func/   the CRM API (POST /api/portal), a Node function bundled from portal-api/portal.ts
 *   .vercel/output/config.json                  headers (security + cache), static/function lookup, SPA fallback
 *
 * Why not an `api/` directory: Vercel detects functions in the uploaded sources BEFORE the build command runs, so a function bundle
 * generated by the build would never be picked up. The Build Output API is read after the build, so it is deterministic.
 * Routing and headers live here (not in vercel.json) so there is exactly one place that defines them.
 */
import { existsSync } from 'node:fs';
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { bundlePortal, STUDIO_ROOT } from './bundle-portal.mjs';

/**
 * Report-Only until it has been checked with a real signed-in Studio session (the Studio bootstrap uses an inline script; a blocking
 * policy must not be switched on by guesswork). The violations show in the browser console, not in a log we can read.
 */
const CSP =
  "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https://*.sanity.io https://*.sanity-cdn.com https://lh3.googleusercontent.com https://avatars.githubusercontent.com; font-src 'self' data: https://*.sanity.io https://fonts.gstatic.com; connect-src 'self' https://*.sanity.io wss://*.api.sanity.io https://*.sanity-cdn.com; frame-src https://*.sanity.io; frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'; worker-src 'self' blob:; manifest-src 'self'";

export const SECURITY_HEADERS = {
  'X-Frame-Options': 'DENY',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
  'X-Robots-Tag': 'noindex, nofollow, noarchive',
  'Content-Security-Policy-Report-Only': CSP,
};

export const ROUTES = [
  { src: '/(.*)', headers: SECURITY_HEADERS, continue: true },
  // index.html (also served for every deep link) must always revalidate so a new deployment is picked up.
  { src: '/(?!static/|api/)(.*)', headers: { 'Cache-Control': 'no-cache' }, continue: true },
  { handle: 'filesystem' },
  // An unknown API path is a 404, never the Studio page; so is a bundle that does not exist (a request during a deployment, or for a
  // hash that was never built): the SPA fallback below must not answer it with index.html under a JavaScript URL.
  { src: '/api/(.*)', status: 404, headers: { 'Cache-Control': 'private, no-store, max-age=0' } },
  { src: '/static/(.*)', status: 404, headers: { 'Cache-Control': 'no-store' } },
  { src: '/(.*)', dest: '/index.html' },
  // Only after a file was really found: Sanity names its bundles by content hash, so these never change. Placed in the "hit"
  // phase so that the long cache lifetime can never be attached to a miss.
  { handle: 'hit' },
  { src: '/static/(.*)', headers: { 'Cache-Control': 'public, max-age=31536000, immutable' }, continue: true },
];

export const FUNCTION_CONFIG = {
  runtime: 'nodejs22.x',
  handler: 'index.mjs',
  launcherType: 'Nodejs',
  shouldAddHelpers: false,
  shouldAddSourcemapSupport: false,
  maxDuration: 15,
  regions: ['sin1'],
};

export async function writeOutput() {
  const dist = join(STUDIO_ROOT, 'dist');
  if (!existsSync(join(dist, 'index.html'))) {
    console.error('dist/index.html is missing: run `sanity build` first (npm run build does).');
    process.exit(1);
  }

  const output = join(STUDIO_ROOT, '.vercel', 'output');
  await rm(output, { recursive: true, force: true });
  await mkdir(join(output, 'static'), { recursive: true });
  await cp(dist, join(output, 'static'), { recursive: true });

  const fn = join(output, 'functions', 'api', 'portal.func');
  await mkdir(fn, { recursive: true });
  await bundlePortal(join(fn, 'index.mjs'));
  await writeFile(join(fn, '.vc-config.json'), `${JSON.stringify(FUNCTION_CONFIG, null, 2)}\n`);
  await writeFile(join(fn, 'package.json'), '{ "type": "module" }\n');
  await writeFile(join(output, 'config.json'), `${JSON.stringify({ version: 3, routes: ROUTES }, null, 2)}\n`);
  console.log('Build Output API tree written to .vercel/output');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await writeOutput();
